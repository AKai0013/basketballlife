function ordinaryOutcomeCopy(event,option,tier){
 const anchor=ORDINARY_EVENT_SCENE_ANCHORS[event.t];
 const endings=ORDINARY_OUTCOME_ENDINGS[tier]||ORDINARY_OUTCOME_ENDINGS.success;
 const ending=endings[option[2]]||endings.default;
 const action=String(option[0]||"").replace(/[。；，]/g,"");
 return `${anchor}你決定${action}。${ending}`;
}

for(const event of [...events,...PRO_GENERAL_EVENTS]){
 if(!ORDINARY_EVENT_SCENE_ANCHORS[event.t])continue;
 for(const option of event.opts){
  if(option[3])continue;
  option[3]={};
  for(const tier of ["great","success","fail","disaster"])option[3][tier]=ordinaryOutcomeCopy(event,option,tier);
 }
}
